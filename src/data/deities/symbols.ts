export function translateSymbol(value: string): string {
  if (!value) return '';
  const plain = value.replace(/\{@\w+\s+([^}]+)\}/g, (_, body: string) => body.split('|')[0]).trim();
  const found = symbols[plain.toLowerCase()];
  if (found) return found;
  if (plain.includes(' or ')) return plain.split(' or ').map(translateSymbol).join(' или ');
  throw new Error(`Missing deity symbol translation: ${plain}`);
}
