export function formatArtisanToolRules(id: string): string {
  const rules = artisanToolRules[id];
  if (!rules) return '';
  return [
    'Дополнительные механики — «Руководство Занатара обо всём» (XGE), «Владение инструментами».',
    'Эти применения требуют владения инструментами и дополняют правила 2024 года. Для действий, уже описанных выше, используются актуальные правила и Сл.',
    `Связанные навыки. ${rules.skills} Если к проверке применимы и инструмент, и навык, которыми вы владеете, вы получаете Преимущество; бонус мастерства добавляется один раз. По решению мастера успешная проверка также может дать дополнительные сведения.`,
    ...rules.uses,
    `Дополнительные проверки (рекомендуемые Сл.). ${rules.checks}`,
  ].join('\n\n');
}
